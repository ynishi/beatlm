    #[test]
    fn slot_tensors_live_for_the_whole_program_and_share_nothing() {
        let p = program(&DEFAULT_SHAPE, Fusion::On).unwrap();
        let all = tensors(&p, &Numbers::net(&DEFAULT_SHAPE), 3).unwrap();
        let plan = MemoryPlan::new(&all, &DeviceProfile::webgpu_baseline()).unwrap();
        let last = u32::try_from(p.kernels().len() - 1).unwrap();
        let io: Vec<_> = (0..3)
            .flat_map(|slot| [input_id(slot), output_id(slot)])
            .collect();
        assert_eq!(all.len(), p.tensors().len() + 4);
        for id in &io {
            let desc = all.iter().find(|t| t.id == *id).unwrap();
            assert_eq!((desc.first_use, desc.last_use), (0, last));
            let placement = plan.placement(*id).unwrap();
            for other in all.iter().filter(|t| t.id != *id) {
                let q = plan.placement(other.id).unwrap();
                assert!(
                    placement.arena != q.arena
                        || placement.end() <= q.offset
                        || q.end() <= placement.offset,
                    "tensor {} overlaps tensor {}",
                    id.get(),
                    other.id.get()
                );
            }
        }
    }
