    const KRES: TensorId = TensorId::new(4);
    const KH: TensorId = TensorId::new(10);
    const KY: TensorId = TensorId::new(20);
    const KCHAIN: [TensorId; 3] = [TensorId::new(11), TensorId::new(12), TensorId::new(13)];

    /// One heavy operation reading `inputs` and writing `out` elements, with
    /// no epilogue and with each epilogue: every step alone, and a chain of
    /// all four. Each graph comes with values for its inputs and weights.
    fn kernel_cases(
        inputs: &[(TensorId, Vec<f32>)],
        heavy: OpKind,
        out: u32,
    ) -> Vec<(String, Graph, BTreeMap<TensorId, Vec<f32>>)> {
        let relu = |input| OpKind::Relu {
            input,
            elements: out,
        };
        let gelu = |input| OpKind::Gelu {
            input,
            elements: out,
        };
        let scale = |input| OpKind::Scale {
            input,
            factor: -1.5,
            elements: out,
        };
        let add = |input| OpKind::Add {
            a: input,
            b: KRES,
            elements: out,
        };
        let chains: Vec<(&str, Vec<OpKind>)> = vec![
            ("none", vec![]),
            ("relu", vec![relu(KH)]),
            ("gelu", vec![gelu(KH)]),
            ("scale", vec![scale(KH)]),
            ("add", vec![add(KH)]),
            (
                "chain",
                vec![add(KH), relu(KCHAIN[0]), gelu(KCHAIN[1]), scale(KCHAIN[2])],
            ),
        ];
        chains
            .into_iter()
            .map(|(name, steps)| {
                let mut g = Graph::new();
                let mut values: BTreeMap<TensorId, Vec<f32>> = inputs.iter().cloned().collect();
                for (id, v) in inputs {
                    g.tensor(*id, TensorRole::Weight, v.len() as u64).unwrap();
                }
                values.insert(KRES, uniform(77, out as usize, -1.0, 1.0));
                g.tensor(KRES, TensorRole::Input, out.into()).unwrap();
                let outputs: Vec<TensorId> = std::iter::once(KH)
                    .chain(KCHAIN)
                    .take(steps.len())
                    .collect();
                for &t in &outputs {
                    g.tensor(t, TensorRole::Activation, out.into()).unwrap();
                }
                g.tensor(KY, TensorRole::Output, out.into()).unwrap();
                g.push(heavy, if steps.is_empty() { KY } else { KH })
                    .unwrap();
                let mut writes = outputs.iter().skip(1).copied().chain([KY]);
                for step in steps {
                    g.push(step, writes.next().unwrap()).unwrap();
                }
                (name.to_owned(), g, values)
            })
            .collect()
    }

